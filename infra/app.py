"""`cdk synth` entry point (cdk.json runs `python infra/app.py`)."""

import sys
from pathlib import Path

import aws_cdk as cdk
import yaml
from cdk_nag import AwsSolutionsChecks

sys.path.insert(0, str(Path(__file__).resolve().parent))
from stack import ROOT, DeskPlatformStack


def acknowledgements(account: str, region: str) -> dict[str, str]:
    """Each cdk-nag finding the stack accepts, with the reason. Anything new fails the synth."""
    grants = "Generated by a CDK grant for one named bucket, key or function (object paths, key actions, function versions)."
    ids = {
        "AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole]": "Lambda's documented managed policy for writing its own logs.",
        "AwsSolutions-IAM4[Policy::arn:<AWS::Partition>:iam::aws:policy/service-role/AWSLambdaVPCAccessExecutionRole]": "Lambda's documented managed policy for ENIs in a VPC.",
        "AwsSolutions-IAM5[Resource::*]": "X-Ray PutTraceSegments/PutTelemetryRecords take no resource ARN.",
        "AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:bedrock:*::foundation-model/anthropic.*]": "EU cross-region inference routes to Anthropic models in several EU regions; the profile below pins it to EU.",
        f"AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:bedrock:{region}:{account}:inference-profile/eu.anthropic.*]": "Only EU inference profiles for Anthropic models.",
        f"AwsSolutions-IAM5[Resource::arn:<AWS::Partition>:logs:{region}:{account}:log-group:/aws/bedrock-agentcore/runtimes/*]": "The runtime's own log groups, named by AgentCore at creation.",
    }
    for finding in (
        "Action::s3:GetObject*",
        "Action::s3:GetBucket*",
        "Action::s3:List*",
        "Resource::<Documents7E5B2978.Arn>/*",
        "Resource::<SkillsAB0E5508.Arn>/*",
        "Resource::<ToolFnB10B8A8D.Arn>:*",
        "Resource::<DeskRequestInterceptor273A68DC.Arn>:*",
        "Resource::<DeskResponseInterceptor44C78E18.Arn>:*",
        "Resource::<DevRequestInterceptor66539CF0.Arn>:*",
        "Resource::<DevResponseInterceptorE63559B1.Arn>:*",
        "Action::kms:ReEncrypt*",
        "Action::kms:GenerateDataKey*",
    ):
        ids[f"AwsSolutions-IAM5[{finding}]"] = grants
    return {f"AwsSolutions::{k}": v for k, v in ids.items()}


def build(cfg: dict | None = None, outdir: str | None = None) -> tuple[cdk.App, DeskPlatformStack]:
    cfg = cfg or yaml.safe_load((ROOT / "config" / "infra.yaml").read_text())
    app = cdk.App(outdir=outdir) if outdir else cdk.App()
    account = app.node.try_get_context("account") or cfg["account"]
    stack = DeskPlatformStack(app, f"PowerDesk-{cfg['env_name']}", cfg, env=cdk.Environment(account=account, region=cfg["region"]))
    cdk.Tags.of(stack).add("project", "power-desk-agent-platform")
    cdk.Tags.of(stack).add("data-classification", "confidential")
    cdk.Validations.of(app).add_plugins(AwsSolutionsChecks(app))
    for rule, reason in acknowledgements(account, cfg["region"]).items():
        cdk.Validations.of(stack).acknowledge(cdk.Acknowledgment(id=rule, reason=reason))
    return app, stack


if __name__ == "__main__":
    app, _ = build()
    app.synth()
